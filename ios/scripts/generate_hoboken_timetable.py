#!/usr/bin/env python3
"""Extract 33 Street -> Hoboken from PATH's public AEM page models.

Download these public sources, then pass the saved files as arguments:
https://www.panynj.gov/content/path/en/schedules-maps/weekday-schedules.model.json
https://www.panynj.gov/content/path/en/schedules-maps/weekend-schedules.model.json

Only top-level current Saturday/Sunday accordions are read; archived child pages
are deliberately excluded. The five Manhattan station offsets are verified
against every published row before writing the generated Swift table.
"""
import argparse
from datetime import date
import hashlib
from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re


class TableParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows, self.row, self.cell = [], None, None

    def handle_starttag(self, tag, attrs):
        if tag == 'tr':
            self.row = []
        elif tag in ('td', 'th'):
            self.cell = []

    def handle_data(self, data):
        if self.cell is not None:
            self.cell.append(data)

    def handle_endtag(self, tag):
        if tag in ('td', 'th') and self.cell is not None:
            if self.row is not None:
                self.row.append(' '.join(''.join(self.cell).split()))
            self.cell = None
        elif tag == 'tr' and self.row is not None:
            if self.row:
                self.rows.append(self.row)
            self.row = None


def strings(value):
    if isinstance(value, dict):
        for child in value.values():
            yield from strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from strings(child)
    elif isinstance(value, str):
        yield value


def minutes(value):
    match = re.fullmatch(r'(\d{1,2}):(\d{2})\s*([AP]M)', value)
    if not match:
        raise ValueError('Unexpected timetable cell: ' + value)
    hour, minute = int(match[1]), int(match[2])
    if not 1 <= hour <= 12 or not 0 <= minute < 60:
        raise ValueError('Invalid clock: ' + value)
    return hour % 12 * 60 + minute + (720 if match[3] == 'PM' else 0)


def extract(model, expected_day):
    root = model[':items']['root'][':items']
    matches = []
    for container in root.values():
        if not isinstance(container, dict):
            continue
        title = container.get('title', '')
        if expected_day and expected_day not in title:
            continue
        for accordion in container.get(':items', {}).values():
            label = unescape(re.sub('<[^>]+>', '', accordion.get('accordionLabel', ''))).strip()
            if label != '33 Street - Hoboken':
                continue
            parser = TableParser()
            parser.feed(next(s for s in strings(accordion) if '<table' in s))
            assert parser.rows[0][0] == '33 St Departure', parser.rows[0]
            rows = [[minutes(cell) for cell in row] for row in parser.rows[1:]]
            assert rows and all(len(row) == 6 for row in rows)
            assert all([m - row[0] for m in row[:5]] == [0, 1, 2, 4, 5] for row in rows)
            values = [row[0] for row in rows]
            assert values == sorted(set(values)), 'Timetable must be sorted and unique'
            matches.append(values)
    assert len(matches) == 1, f'Expected one current {expected_day or "weekday"} timetable, found {len(matches)}'
    return matches[0]


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('weekday', type=Path)
    args.add_argument('weekend', type=Path)
    args.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'Shared' / 'HobokenTimetable.swift')
    a = args.parse_args()
    weekday, weekend = json.loads(a.weekday.read_text()), json.loads(a.weekend.read_text())
    data = [('weekday', extract(weekday, '')), ('sat', extract(weekend, 'Saturday')), ('sun', extract(weekend, 'Sunday'))]
    header = '// Generated by ios/scripts/generate_hoboken_timetable.py. Do not edit by hand.\n'
    header += f'// Published 33 Street -> Hoboken schedule, retrieved {date.today().isoformat()}.\n'
    header += '// Source: https://www.panynj.gov/path/en/schedules-maps/weekday-schedules.html\n'
    header += '// Source: https://www.panynj.gov/path/en/schedules-maps/weekend-schedules.html\n'
    for label, path in [('weekday', a.weekday), ('weekend', a.weekend)]:
        header += f'// {label} page-model SHA-256: {hashlib.sha256(path.read_bytes()).hexdigest()}\n'
    text = header + '\nextension HobokenSchedule {\n    static let table: [NewportSchedule.DayType: [Int]] = [\n'
    for day, values in data:
        text += '        .' + day + ': [\n'
        for i in range(0, len(values), 18):
            text += '            ' + ', '.join(map(str, values[i:i + 18])) + ',\n'
        text += '        ],\n'
        print(day, len(values), 'trains;', values[0], 'through', values[-1], 'minutes after midnight')
    a.output.write_text(text + '    ]\n}\n')


if __name__ == '__main__':
    main()
